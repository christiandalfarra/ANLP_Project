# -------------------------------------------------- 4 · Experimental design
s = add_slide()
title_bar(s, "Design: 2 input pipelines × 2 learning paradigms",
          "3 architectures · 3 prompt styles · 11 evaluated conditions")
rows = [
    ["", "Chunk + aggregate", "Long-context (16,384 tokens)"],
    ["Prompting\n(zero / few / CoT)", "FLAN-T5-Large (512)\nBART-Large-CNN (1,024)", "LED-base-16384"],
    ["Fine-tuning", "BART as the merge step\n(“chunk-merger” recipe)", "LED on 8,192-token\nrandom windows"],
]
tbl = s.shapes.add_table(3, 3, Inches(0.8), Inches(1.6), Inches(11.7), Inches(3.1)).table
tbl.columns[0].width = Inches(2.9)
tbl.columns[1].width = Inches(4.4)
tbl.columns[2].width = Inches(4.4)
for i, row in enumerate(rows):
    for j, cell_text in enumerate(row):
        cell = tbl.cell(i, j)
        cell.fill.solid()
        cell.fill.fore_color.rgb = NAVY if (i == 0 or j == 0) else WHITE
        tfc = cell.text_frame
        tfc.word_wrap = True
        for k, line in enumerate(cell_text.split("\n")):
            p = tfc.paragraphs[0] if k == 0 else tfc.add_paragraph()
            hdr = i == 0 or j == 0
            set_run(p.add_run(), line, 15 if hdr else 14,
                    WHITE if hdr else DARK, bold=hdr)
bullets(s, [
    [("Chunk + aggregate: ", {"bold": True}),
     ("segment-aligned chunks with 1-segment overlap → per-chunk summary → merge → BoW-cosine dedup.", {})],
    [("Long-context: ", {"bold": True}),
     ("whole transcript in one LED forward pass; global attention on BOS; gradient checkpointing on a T4.", {})],
    [("All experiments on free-tier Kaggle (1× T4, 15.6 GB); seeds fixed; every prediction saved to disk.", {})],
], y=Inches(5.0), size=16)
footer(s, 4)

