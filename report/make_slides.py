from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

NAVY = RGBColor(0x0A, 0x3D, 0x7A)
DARK = RGBColor(0x22, 0x22, 0x22)
GREY = RGBColor(0x66, 0x66, 0x66)
RED = RGBColor(0xB0, 0x00, 0x00)
LIGHT = RGBColor(0xF2, 0xF5, 0xFA)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)

SW, SH = Inches(13.333), Inches(7.5)

prs = Presentation()
prs.slide_width, prs.slide_height = SW, SH
BLANK = prs.slide_layouts[6]


def add_slide():
    return prs.slides.add_slide(BLANK)


def textbox(slide, x, y, w, h):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    return tf


def set_run(r, text, size, color=DARK, bold=False, italic=False, font="Calibri"):
    r.text = text
    r.font.size = Pt(size)
    r.font.color.rgb = color
    r.font.bold = bold
    r.font.italic = italic
    r.font.name = font


def title_bar(slide, text, kicker=None):
    bar = slide.shapes.add_shape(1, 0, 0, SW, Inches(1.1))  # 1 = rectangle
    bar.fill.solid()
    bar.fill.fore_color.rgb = NAVY
    bar.line.fill.background()
    tf = bar.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0.55)
    tf.margin_top = Inches(0.12)
    p = tf.paragraphs[0]
    set_run(p.add_run(), text, 27, WHITE, bold=True)
    if kicker:
        p2 = tf.add_paragraph()
        set_run(p2.add_run(), kicker, 13, RGBColor(0xC9, 0xD8, 0xEC))


def bullets(slide, items, x=Inches(0.6), y=Inches(1.45), w=Inches(12.1),
            h=Inches(5.6), size=17):
    tf = textbox(slide, x, y, w, h)
    first = True
    for item in items:
        if isinstance(item, str):
            item = [(item, {})]
        level = item[0][1].pop("level", 0) if item else 0
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.level = level
        p.space_after = Pt(8)
        for text, kw in item:
            sz = kw.pop("size", size - 2 * level)
            set_run(p.add_run(), text, sz, **kw)
    return tf


def footer(slide, n):
    tf = textbox(slide, SW - Inches(1.0), SH - Inches(0.42), Inches(0.8), Inches(0.3))
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.RIGHT
    set_run(p.add_run(), str(n), 11, GREY)


def quote_box(slide, x, y, w, h, label, text, label_color=NAVY):
    box = slide.shapes.add_shape(1, x, y, w, h)
    box.fill.solid()
    box.fill.fore_color.rgb = LIGHT
    box.line.color.rgb = RGBColor(0xC5, 0xD0, 0xE0)
    box.line.width = Pt(0.75)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0.18)
    tf.margin_right = Inches(0.18)
    tf.margin_top = Inches(0.1)
    p = tf.paragraphs[0]
    set_run(p.add_run(), label, 13, label_color, bold=True)
    p2 = tf.add_paragraph()
    set_run(p2.add_run(), text, 13, DARK, italic=True)


